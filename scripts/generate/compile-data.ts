import books from '../../data/research/books.json' with { type: 'json' };
import works from '../../data/research/works.json' with { type: 'json' };
import BofM from '../../data/verses/BofM.json' with { type: 'json' };
import DnC from '../../data/verses/D&C.json' with { type: 'json' };
import Didache from '../../data/verses/Didache.json' with { type: 'json' };
import KJV from '../../data/verses/KJV.json' with { type: 'json' };
import KJVA from '../../data/verses/KJVA.json' with { type: 'json' };
import PGP from '../../data/verses/PGP.json' with { type: 'json' };
import getChapterCount from '../../src/lib/getChapterCount.ts';
import getVerseCounts from '../../src/lib/getVerseCounts.ts';
import type {
  RawBookShape,
  RawWorkShape,
  VerseShape,
} from '../../src/types/data-shapes.ts';

const versesByWorkName: Record<string, VerseShape[]> = {
  // @ts-expect-error BofM is too large for TS to infer
  BofM: BofM.verses as VerseShape[],
  'D&C': DnC.verses as VerseShape[],
  Didache: Didache.verses as VerseShape[],
  // @ts-expect-error KJV is too large for TS to infer
  KJV: KJV.verses as VerseShape[],
  KJVA: KJVA.verses as VerseShape[],
  PGP: PGP.verses as VerseShape[],
};

// const dummyWork = {
//
// }

const s = (v: any) => JSON.stringify(v, null, 2);

main().catch(console.error);

async function main() {
  const tsDest = Bun.file(
    `${import.meta.dir}/../../data/compiled/books-and-works.ts`,
  );
  const jsonDest = Bun.file(
    `${import.meta.dir}/../../data/compiled/books-and-works.json`,
  );

  const worksWithData = (works as unknown as RawWorkShape[]).filter(
    (w) => w.hasData,
  );
  const booksWithData = (books as unknown as RawBookShape[])
    .filter((b) => b.hasData)
    .map((b) => {
      if (!(b.workOsisID in versesByWorkName)) {
        throw new Error(
          `Unable to find workOsisID "${b.workOsisID}" verses for book "${b.bookOsisID}"`,
        );
      }
      const chapterCount =
        getChapterCount(b.bookOsisID, versesByWorkName[b.workOsisID] || []) ||
        -1;
      if (chapterCount === -1) {
        throw new Error(
          `Unable to get chapterCount for book "${b.bookOsisID}"`,
        );
      }
      const verseCounts =
        getVerseCounts(b.bookOsisID, versesByWorkName[b.workOsisID] || []) ||
        [];
      if (verseCounts.length === 0) {
        throw new Error(`Unable to get verseCounts for book "${b.bookOsisID}"`);
      }
      return {
        workOsisID: b.workOsisID,
        bookName: b.bookName,
        bookSubtitle: b.bookSubtitle,
        bookOsisID: b.bookOsisID,
        paratext: b.paratext,
        groups: b.groups,
        aliases: b.aliases,
        chapterLabel: b.chapterLabel,
        verseLabel: b.verseLabel,
        authors: b.authors,
        traditions: b.traditions,
        dateEarliest: b.dateEarliest,
        dateLatest: b.dateLatest,
        chapterCount,
        verseCounts,
        hasData: true,
      };
    });
  const jsonData = {
    books: booksWithData,
    works: worksWithData,
    worksLookup: {} as Record<string, number>,
    booksLookup: {} as Record<string, number>,
    groupsLookup: {} as Record<string, number[]>,
  };
  const output = [];

  // works
  output.push(`// Auto-generated on ${new Date().toISOString()}`);
  output.push(`// DO NOT EDIT THIS FILE`);
  output.push(
    `
import type {
  BookShape,
  WorkShape,
} from '../../src/types/data-shapes.ts';
`.trim(),
  );
  const formatedWorks = worksWithData.map((work) => ({
    ...work,
    books: [],
    bookCount: 0,
  }));
  output.push(`export const works : WorkShape[] = ${s(formatedWorks)};`);
  output.push(`const w = works;`);
  output.push(`export const worksLookup : Record<string, WorkShape> = {`);
  for (let i = 0; i < worksWithData.length; i++) {
    const work = worksWithData[i];
    const titleUpper = work.workTitle.toUpperCase();
    output.push(`  ${s(titleUpper)}: w[${i}],`);
    const osisIdUpper = work.workOsisID.toUpperCase();
    if (osisIdUpper !== titleUpper) {
      output.push(`  ${s(osisIdUpper)}: w[${i}],`);
    }
    for (const alias of work.aliases) {
      const aliasUpper = alias.toUpperCase();
      if (aliasUpper !== titleUpper && aliasUpper !== osisIdUpper) {
        output.push(`  ${s(aliasUpper)}: w[${i}],`);
      }
    }
  }
  output.push(`};`);

  // books
  const formattedBooks = booksWithData.map((book) => ({
    ...book,
    work: null,
  }));
  output.push(`export const books : BookShape[] = ${s(formattedBooks)};`);
  output.push(`const b = books;`);
  output.push(`export const booksLookup : Record<string, BookShape> = {`);
  for (let i = 0; i < booksWithData.length; i++) {
    const book = booksWithData[i];
    const nameUpper = book.bookName.toUpperCase();
    const osisIdUpper = book.bookOsisID.toUpperCase();
    const paraUpper = String(book.paratext || '').toUpperCase();
    output.push(`  ${s(nameUpper)}: b[${i}],`);
    if (osisIdUpper !== nameUpper) {
      output.push(`  ${s(book.bookOsisID.toUpperCase())}: b[${i}],`);
    }
    if (paraUpper && paraUpper !== nameUpper && paraUpper !== osisIdUpper) {
      output.push(`  ${s(paraUpper)}: b[${i}],`);
    }
    for (const alias of book.aliases) {
      const aliasUpper = String(alias || '').toUpperCase();
      if (
        aliasUpper === nameUpper ||
        aliasUpper === osisIdUpper ||
        aliasUpper === paraUpper
      ) {
        continue;
      }
      output.push(`  ${s(aliasUpper)}: b[${i}],`);
    }
  }
  output.push(`};`);
  // groups lookup
  const groups: Record<string, number[]> = {};
  for (let i = 0; i < booksWithData.length; i++) {
    for (const group of booksWithData[i].groups) {
      const groupUpper = group.toUpperCase();
      if (!(groupUpper in groups)) {
        groups[groupUpper] = [];
      }
      groups[groupUpper].push(i);
    }
  }
  jsonData.groupsLookup = groups;
  output.push(`export const groupsLookup : Record<string, BookShape[]> = {`);
  for (const [nameUpper, bookIdxs] of Object.entries(groups)) {
    output.push(`  ${s(nameUpper)}: [`);
    for (const i of bookIdxs) {
      output.push(`    b[${i}],`);
    }
    output.push(`  ],`);
  }
  output.push(`};`);
  output.push(
    `
// Add cyclical data    
for (const book of books) {
  const work = worksLookup[book.workOsisID.toUpperCase()];
  if (!work) {
    console.error(\`Unable to find work for book \${book.bookOsisID} with work \${book.workOsisID}\`);
    continue;
  }
  if (!work.books) {
    work.books = [];
  }
  work.books.push(book);
  book.work = work;
}
for (const work of works) {
  work.bookCount = work.books.length;
}
`.trim(),
  );
  // write it all
  await tsDest.write(output.join('\n'));
  await jsonDest.write(s(jsonData));
  console.log('wrote to ts and json');
}
